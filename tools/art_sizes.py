#!/usr/bin/env python3
"""art_sizes.py — writes live/sizes.js (display sizes in view px) from the measured art in art/gen (run from the project root, after the art changes).
Obstacle items share one scale (K_ITEM source px → view px); people have fixed heights; the card is 290 wide; the door opening is measured from door_frame's alpha."""
import json, os
import numpy as np
from PIL import Image
K_ITEM = 0.58
TOPS = ['top_queue', 'top_stamp', 'top_pct', 'top_balloon', 'top_tag', 'top_scroll', 'top_phone', 'top_break']
BOTS = ['bot_ticket', 'bot_papers', 'bot_till', 'bot_piggy', 'bot_turnstile', 'bot_magnifier', 'bot_folders', 'bot_window']
PEOPLE = ['man_sit', 'woman_sit', 'man_stand', 'old_cane', 'kid_stand']; K_PEOPLE = 0.62
def bbox(n):
    f = os.path.join('art', 'gen', n + '.png')
    if not os.path.exists(f): return None
    return Image.open(f).convert('RGBA').getchannel('A').point(lambda v: 255 if v > 24 else 0).getbbox()
S = {'hand': [0, 190], 'card': [290, 0], 'coin': [64, 64]}
for n in TOPS + BOTS:
    b = bbox(n)
    if b: S[n] = [round((b[2] - b[0] + 8) * K_ITEM), 0]
for n in PEOPLE:
    b = bbox(n)
    if b: S[n] = [0, round((b[3] - b[1] + 8) * K_PEOPLE)]
out = {}
f = os.path.join('art', 'gen', 'door_frame.png')
if os.path.exists(f):
    a = np.array(Image.open(f).convert('RGBA'))[:, :, 3] < 24; H, W = a.shape
    # the opening = the transparent region connected to the image centre
    from scipy import ndimage
    lab, n = ndimage.label(a); c = lab[H // 2, W // 2]
    if c:
        ys, xs = np.where(lab == c); out['open'] = [round(xs.min() / W, 4), round(ys.min() / H, 4), round((xs.max() + 1) / W, 4), round((ys.max() + 1) / H, 4)]
        out['aspect'] = round(W / H, 4)
S['door'] = out
S['lamps'] = {'x': [[0.052, 0.46], [0.543, 0.956]], 'y': [0.703, 0.730]}   # lamp bars of ceiling_tile (fractions of the tile), measured once
js = '// in-game sprite sizes in VIEW px: { name: [w, h] } — 0 = keep the texture aspect. Generated by tools/art_sizes.py (obstacle items share one scale).\n'
js += 'window.SIZES = {\n' + ''.join(f'  {k}: {json.dumps(v)},\n' for k, v in S.items()) + '};\n'
open(os.path.join('live', 'sizes.js'), 'w', encoding='utf-8').write(js); print(js)
